.DEFINE PORTB_TR_BIT 3 ; PortB TR pin input
.DEFINE PORTB_TL_BIT 2 ; PortB TL pin input
.DEFINE PORTB_RT_BIT 1 ; PortB RIGHT pin input
.DEFINE PORTB_LT_BIT 0 ; PortB LEFT pin input

.DEFINE PORTB_TH 1<<PORTB_TH_BIT
